const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const M=require('./logica.js');
const courses=vm.runInNewContext(fs.readFileSync(path.join(__dirname,'datos.js'),'utf8')+';RAMOS');
const get=id=>courses.find(c=>c.id===id);
const state=M.initial();
const approve=id=>M.setStatus(state,get(id),'approved',courses);

assert.equal(courses.length,52);
assert.equal(new Set(courses.map(c=>c.id)).size,52);
assert.equal(courses.reduce((sum,c)=>sum+c.credits,0),500);
function visit(id,trail=[]) {
  assert.ok(get(id),'Todos los prerrequisitos deben existir');
  assert.ok(!trail.includes(id),'No debe haber ciclos');
  get(id).requires.forEach(r=>visit(r,[...trail,id]));
}
courses.forEach(c=>visit(c.id));
assert.equal(M.status(state,get('s2r1')),'locked');
assert.throws(()=>approve('s2r1'));
approve('s1r1'); approve('s2r1'); approve('s3r1');
assert.equal(M.status(state,get('s4r1')),'locked','Estadística sola no abre Métodos');
approve('s2r2'); approve('s3r2');
assert.equal(M.status(state,get('s4r1')),'pending');
approve('s4r1'); approve('s5r1'); approve('s6r1'); approve('s7r1');
assert.equal(M.status(state,get('s8r1')),'pending');
approve('s4r2'); approve('s6r2');
assert.equal(M.status(state,get('s8r2')),'locked','Capstone necesita dos requisitos');
approve('s1r3'); approve('s3r3'); approve('s5r3'); approve('s6r3');
assert.equal(M.status(state,get('s8r2')),'pending'); approve('s8r2');
const reset=M.setStatus(state,get('s1r3'),'pending',courses);
assert.ok(reset.includes('s8r2'),'Desmarcar propaga por la cadena');
assert.equal(M.status(state,get('s8r2')),'locked');
assert.equal(M.status(state,get('s6r2')),'approved','No borra ramas independientes');
approve('s2r3'); assert.equal(M.status(state,get('s7r2')),'pending');
approve('s2r4'); approve('s4r4'); assert.equal(M.status(state,get('s5r4')),'pending');
approve('s1r2'); assert.equal(M.status(state,get('s4r3')),'pending');
M.move(state,get('s8r2'),1);
assert.equal(M.semester(state,get('s8r2')),1);
assert.ok(M.conflicts(state,get('s8r2'),courses).includes('s6r3'));
assert.equal(M.status(state,get('s8r2')),'locked','Mover no aprueba');
assert.throws(()=>M.move(state,get('s8r2'),0));
state.courses.s3r5={name:'Fotografía',semester:8,status:'approved'};
const restored=M.validate(JSON.parse(JSON.stringify(state)),courses);
assert.deepEqual(restored,state);
assert.equal(M.name(restored,get('s3r5')),'Fotografía');
assert.equal(get('s3r5').name,'Formación General · Artes');
assert.throws(()=>M.validate({...state,semesters:500},courses));
assert.throws(()=>M.validate({...state,courses:{fake:{status:'approved'}}},courses));
assert.throws(()=>M.validate({...state,courses:{s1r1:{status:'inventado'}}},courses));
assert.throws(()=>M.validate({...state,courses:{s1r1:{name:'No editable'}}},courses));
const all=M.initial();
courses.forEach(c=>M.setStatus(all,c,'approved',courses));
assert.equal(courses.filter(c=>M.status(all,c)==='approved').length,52);
for(const file of ['datos.js','logica.js','app.js']) new vm.Script(fs.readFileSync(path.join(__dirname,file),'utf8'));
console.log('OK: datos, grafo, cadenas, requisitos dobles, revocación, movimientos, nombres, respaldos y sintaxis.');
// Una futura carrera puede comenzar con ocho semestres sin heredar los diez de ADP.
const shorter=M.initial(8);
assert.equal(M.validate(shorter,courses,8).semesters,8);
assert.throws(()=>M.validate({...shorter,semesters:7},courses,8));
const catalog=vm.runInNewContext(fs.readFileSync(path.join(__dirname,'datos.js'),'utf8')+'\n'+fs.readFileSync(path.join(__dirname,'carreras.js'),'utf8')+';CARRERAS');
assert.equal(catalog[0].courses.length,52);
assert.equal(new Set(catalog.map(c=>c.id)).size,catalog.length);
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
for(const file of ['estilos.css','datos.js','carreras.js','logica.js','app.js']) assert.ok(html.includes(file));
assert.ok(!html.includes('Tu carrera, paso a paso.'));
assert.ok(!html.includes('Herramienta personal de planificación'));
console.log('OK: catálogo de carreras, semestres configurables y referencias de la nueva interfaz.');
const customState=M.initial();
const extra={id:'custom-test',name:'Mi ramo',code:'TEST',credits:5,sem:2,cat:'fg',requires:['s1r1'],editable:true};
customState.customCourses.push(extra);
const validated=M.validate(JSON.parse(JSON.stringify(customState)),courses);
assert.equal(validated.customCourses.length,1);
assert.equal(M.status(validated,extra),'locked');
M.setStatus(validated,get('s1r1'),'approved',[...courses,extra]);
assert.equal(M.status(validated,extra),'pending');
M.setStatus(validated,extra,'approved',[...courses,extra]);
assert.equal(M.validate(JSON.parse(JSON.stringify(validated)),courses).courses[extra.id].status,'approved');
M.move(validated,extra,6);
assert.equal(M.semester(M.validate(validated,courses),extra),6);
assert.throws(()=>M.validate({...customState,customCourses:[extra,extra]},courses));
assert.throws(()=>M.validate({...customState,customCourses:[{...extra,requires:['custom-test']}]},courses));
assert.throws(()=>M.validate({...customState,customCourses:[{...extra,requires:['missing']}]},courses));
assert.throws(()=>M.validate({...customState,customCourses:[{...extra,credits:-1}]},courses));
const legacy={version:2,semesters:10,courses:{s1r1:{status:'approved'}}};
assert.equal(M.validate(legacy,courses).customCourses.length,0);
assert.equal(M.validate(legacy,courses).courses.s1r1.status,'approved');
const resetState=M.initial(10);
assert.equal(resetState.customCourses.length,0);
assert.equal(Object.keys(resetState.courses).length,0);
assert.equal(resetState.semesters,10);
console.log('OK: ramos personalizados, respaldos antiguos, desbloqueos, validación y estado de reinicio.');
